# Centers an Alacritty window on its monitor and brings it to the foreground.
#   -ProcessId <pid>  : focus the window of this process (Runner Terminal from the backend)
#   -Ancestor         : walk up the parent processes until alacritty.exe (fzf window from the launcher)
# Windows blocks SetForegroundWindow for background processes (foreground lock),
# hence the Alt key trick before the call.
param(
    [int]$ProcessId = 0,
    [switch]$Ancestor
)

$code = @'
using System;
using System.Runtime.InteropServices;
public class FocusWin32 {
    [DllImport("user32.dll")] public static extern bool SetForegroundWindow(IntPtr hWnd);
    [DllImport("user32.dll")] public static extern bool BringWindowToTop(IntPtr hWnd);
    [DllImport("user32.dll")] public static extern bool ShowWindow(IntPtr hWnd, int nCmdShow);
    [DllImport("user32.dll")] public static extern bool IsIconic(IntPtr hWnd);
    [DllImport("user32.dll")] public static extern void keybd_event(byte bVk, byte bScan, uint dwFlags, UIntPtr dwExtraInfo);
    [DllImport("user32.dll")] public static extern bool GetWindowRect(IntPtr hWnd, out RECT lpRect);
    [DllImport("user32.dll")] public static extern bool SetWindowPos(IntPtr hWnd, IntPtr hWndInsertAfter, int X, int Y, int cx, int cy, uint uFlags);
    public struct RECT { public int Left, Top, Right, Bottom; }
}
'@
Add-Type -TypeDefinition $code -ErrorAction SilentlyContinue
Add-Type -AssemblyName System.Windows.Forms

if ($Ancestor) {
    $current = $PID
    for ($i = 0; $i -lt 10 -and $current; $i++) {
        $proc = Get-CimInstance Win32_Process -Filter "ProcessId = $current"
        if (-not $proc) { break }
        if ($proc.Name -eq "alacritty.exe") { $ProcessId = $current; break }
        $current = $proc.ParentProcessId
    }
}
if (-not $ProcessId) { exit }

# Wait until the real window exists. Right after start, MainWindowHandle can still
# point to a 16x16 winit helper window, so also wait for a plausible size.
$hwnd = [IntPtr]::Zero
$rect = New-Object FocusWin32+RECT
for ($i = 0; $i -lt 100; $i++) {
    $p = Get-Process -Id $ProcessId -ErrorAction SilentlyContinue
    if (-not $p) { exit }
    $h = $p.MainWindowHandle
    if ($h -ne [IntPtr]::Zero -and [FocusWin32]::GetWindowRect($h, [ref]$rect) -and ($rect.Right - $rect.Left) -gt 100) {
        $hwnd = $h
        break
    }
    Start-Sleep -Milliseconds 50
}
if ($hwnd -eq [IntPtr]::Zero) { exit }

if ([FocusWin32]::IsIconic($hwnd)) { [FocusWin32]::ShowWindow($hwnd, 9) | Out-Null }

# Center on the monitor the window is on (Alacritty itself only knows a fixed start position)
if ([FocusWin32]::GetWindowRect($hwnd, [ref]$rect)) {
    $area = [System.Windows.Forms.Screen]::FromHandle($hwnd).WorkingArea
    $width = $rect.Right - $rect.Left
    $height = $rect.Bottom - $rect.Top
    $x = $area.X + [math]::Floor(($area.Width - $width) / 2)
    $y = $area.Y + [math]::Floor(($area.Height - $height) / 2)
    if ($rect.Left -ne $x -or $rect.Top -ne $y) {
        # SWP_NOSIZE | SWP_NOZORDER
        [FocusWin32]::SetWindowPos($hwnd, [IntPtr]::Zero, $x, $y, 0, 0, 0x0001 -bor 0x0004) | Out-Null
        # Remember as start position, so the next window opens centered right away
        $posFile = Join-Path $PSScriptRoot "window-position.toml"
        Set-Content -Path $posFile -Value "# Generated by focus_window.ps1, safe to delete`n[window]`nposition = { x = $x, y = $y }"
    }
}

# Briefly press/release Alt so Windows allows the focus change
[FocusWin32]::keybd_event(0x12, 0, 0, [UIntPtr]::Zero)
[FocusWin32]::keybd_event(0x12, 0, 2, [UIntPtr]::Zero)

[FocusWin32]::BringWindowToTop($hwnd) | Out-Null
[FocusWin32]::SetForegroundWindow($hwnd) | Out-Null
